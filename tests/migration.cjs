// Run with: node tests/migration.cjs (no dependency installation required).
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../index.html'), 'utf8').match(/<script>([\s\S]*?)<\/script>/)[1];
const context = vm.createContext({crypto:require('node:crypto').webcrypto});
vm.runInContext(source.slice(0, source.indexOf('let state,'))+'\nglobalThis.api={defaults,migrate,validate,catalog:PACKING_DEFAULTS};',context);
const {defaults,migrate,validate,catalog}=context.api;
const clone=x=>JSON.parse(JSON.stringify(x));
const fresh=clone(defaults());
assert.equal(fresh.packing.length,12);
assert.equal(fresh.packing.flatMap(g=>g.items).length,204);
assert.equal(new Set(fresh.packing.flatMap(g=>g.items.map(i=>i.id))).size,204);
assert.equal(fresh.packing.flatMap(g=>g.items).filter(i=>i.name==='물티슈').length,2);
assert.ok(fresh.packing.flatMap(g=>g.items).every(i=>i.done===false));
const freshBefore=clone(fresh);
assert.deepEqual(clone(migrate(fresh)),freshBefore,'repeat migration must be idempotent');
const legacy={version:1,packing:[{id:'custom',name:'나의 준비물',collapsed:true,items:[{id:'x',name:'내가 수정한 준비물',done:true},{id:'y',name:'보조배터리',done:true},{id:'z',name:'신분증 · 운전면허증',done:true}]},{id:'old',name:'기본 준비물',items:[]}],places:[{id:'p',name:'직접 만든 장소',items:[{id:'pi',name:'카페',done:true,note:'내 메모',url:'https://example.com'}]}],days:clone(fresh.days)};
const before=clone(legacy);
migrate(validate(legacy));
assert.deepEqual(legacy.places,before.places);
assert.deepEqual(legacy.days,before.days);
assert.deepEqual(legacy.packing.slice(0,2).map(g=>[g.id,g.name,g.collapsed]),before.packing.map(g=>[g.id,g.name,g.collapsed]));
assert.equal(legacy.packing[0].items[0].name,'내가 수정한 준비물');
assert.equal(legacy.packing[0].items[0].done,true);
assert.equal(legacy.packing.flatMap(g=>g.items).filter(i=>i.name==='보조배터리').length,1);
assert.equal(legacy.packing[0].items[1].done,true);
assert.deepEqual(legacy.packing[0].items[2],before.packing[0].items[2]);
assert.ok(!legacy.packing.flatMap(g=>g.items).some(i=>i.name==='충전기 · 보조배터리'),'old deleted defaults must not reappear');
assert.deepEqual(clone(migrate(clone(legacy))),clone(legacy),'legacy migration must not duplicate');
// User edits, deletes, collapses and reorders the expanded catalog.
const edited=clone(defaults());
const deletedGroup=edited.packing.splice(1,1)[0];
const deletedItem=edited.packing[0].items.shift();
const renamed=edited.packing[0].items[0];renamed.name='내 운전면허증';renamed.done=true;
edited.packing[0].name='내 필수품';edited.packing[0].collapsed=true;
edited.packing.reverse();edited.packing.at(-1).items.reverse();
const saved=clone(edited);
assert.deepEqual(clone(migrate(validate(clone(edited)))),saved,'edits/deletes/order survive reload and backup restore');
const future=clone(catalog);
future[0].items.push({id:'packing-essentials-future',name:'새 기본 준비물'});
future[1].items.push({id:'packing-clothing-future',name:'삭제한 카테고리의 새 항목'});
future.push({id:'packing-future',name:'추가 카테고리',items:[{id:'packing-future-01',name:'향후 항목'}]});
migrate(edited,future);
assert.ok(!edited.packing.some(g=>g.id===deletedGroup.id));
assert.ok(!edited.packing.flatMap(g=>g.items).some(i=>i.id===deletedItem.id));
assert.equal(edited.packing.flatMap(g=>g.items).filter(i=>i.id==='packing-essentials-future').length,1);
assert.equal(edited.packing.at(-1).id,'packing-future');
const futureBefore=clone(edited);
assert.deepEqual(clone(migrate(edited,future)),futureBefore);
assert.throws(()=>validate({...fresh,packingDefaults:{groups:[],items:'broken'}}));
assert.throws(()=>validate({...fresh,version:999}));
console.log('PASS: 12 categories / 204 items; legacy migration, exact matching, edits, deletions, order, future additions, repeatability, backup metadata validation');
